import { z } from 'zod';
import { UuidSchema } from './common.js';

/** The app sends a heartbeat this often while a video is playing on screen. */
export const HEARTBEAT_INTERVAL_MS = 5_000;
export const MIN_POOL_BUDGET_MINOR = 10_000; // ₹100
export const MAX_POOL_BUDGET_MINOR = 100_000_000; // ₹10,00,000

const isoDate = z.iso.datetime({ offset: true, message: 'Invalid date' });

export const CreateRewardPoolSchema = z
  .object({
    eventId: UuidSchema,
    title: z.string().trim().min(3).max(80),
    sponsorName: z.string().trim().min(2).max(80),
    rules: z.string().trim().max(2000).default(''),
    budgetMinor: z
      .number()
      .int()
      .min(MIN_POOL_BUDGET_MINOR, 'Minimum pool is ₹100')
      .max(MAX_POOL_BUDGET_MINOR, 'Maximum pool is ₹10,00,000'),
    perVideoCapBps: z.number().int().min(500).max(10_000).default(2_500),
    minQualifiedViewers: z.number().int().min(1).max(100).default(3),
    /** Defaults: event start → 7 days after the event ends. */
    startsAt: isoDate.optional(),
    endsAt: isoDate.optional(),
  })
  .refine((p) => !p.startsAt || !p.endsAt || Date.parse(p.endsAt) > Date.parse(p.startsAt), {
    message: 'End must be after start',
    path: ['endsAt'],
  });
export type CreateRewardPoolInput = z.input<typeof CreateRewardPoolSchema>;

export const StartWatchSchema = z.object({
  postId: UuidSchema,
  /** Random per-install id generated by the app (hashed server-side). */
  deviceId: z.string().min(8).max(100),
});
export type StartWatchInput = z.infer<typeof StartWatchSchema>;

export const HeartbeatSchema = z.object({
  positionMs: z
    .number()
    .int()
    .min(0)
    .max(24 * 3_600_000),
  playing: z.boolean(),
  foreground: z.boolean(),
});
export type HeartbeatInput = z.infer<typeof HeartbeatSchema>;

// ───────────── Response shapes ─────────────

export interface WatchSessionDto {
  sessionId: string;
  heartbeatIntervalMs: number;
  /** Whether this viewing can count toward creator rewards (informational). */
  qualifying: boolean;
}

export type RewardPoolStatusDto =
  'DRAFT' | 'FUNDED' | 'ACTIVE' | 'COMPLETED' | 'DISTRIBUTED' | 'CANCELLED';

export interface RewardPoolDto {
  id: string;
  event: { id: string; title: string };
  title: string;
  sponsorName: string;
  rules: string;
  budgetMinor: number;
  currency: string;
  perVideoCapBps: number;
  minQualifiedViewers: number;
  startsAt: string;
  endsAt: string;
  status: RewardPoolStatusDto;
  /** Distributed so far (after distribution) or currently estimated (while active). */
  allocatedMinor: number;
  unallocatedMinor: number | null;
  viewer: { canManage: boolean; canFund: boolean };
}

export interface LeaderboardEntry {
  rank: number;
  postId: string;
  thumbUrl: string | null;
  creator: {
    id: string;
    displayName: string | null;
    username: string | null;
    avatarUrl: string | null;
  };
  qualifiedSeconds: number;
  qualifiedViewers: number;
  /** Final share (distributed) or estimate (active). */
  shareMinor: number;
  eligible: boolean;
  capped: boolean;
}

export interface RewardPoolDetail extends RewardPoolDto {
  leaderboard: LeaderboardEntry[];
  /** True while estimates are shown (not final). */
  estimated: boolean;
  stats: {
    qualifiedSeconds: number;
    qualifiedViewers: number;
    eligibleVideos: number;
    flaggedSessions: number;
  } | null;
}

export interface EventLeaderboards {
  watchTime: {
    creatorId: string;
    displayName: string | null;
    username: string | null;
    avatarUrl: string | null;
    qualifiedSeconds: number;
  }[];
  mostLoved: {
    postId: string;
    thumbUrl: string | null;
    creatorName: string | null;
    likes: number;
  }[];
  mostSupported: {
    creatorId: string;
    displayName: string | null;
    username: string | null;
    avatarUrl: string | null;
    supporters: number;
  }[];
}
